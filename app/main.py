@app.post("/api/settings/update/now")
def update_now():
    """Trigger a one-off git pull now. If anything changed the process will
    exit so systemd brings it back with the new code; the response is sent
    *before* exit so the UI sees success."""
    changed, msg, after = updater.pull_now()
    response = {"ok": True, "changed": changed, "message": msg, "local": after}
    if changed:
        # Schedule exit AFTER the response is flushed to the client.
        def _bye():
            import time, os as _os
            time.sleep(1)
            _os.kill(_os.getpid(), 15)  # SIGTERM, systemd restarts
        import threading; threading.Thread(target=_bye, daemon=True).start()
    return response


@app.get("/api/settings/ssl")
def get_ssl_status(request: Request):
    """Snapshot of TLS state. The 'current_scheme' is how *this request* arrived
    — it's the most reliable signal that HTTPS is actually serving."""
    cert_path = tls.CERT_PATH
    key_path = tls.KEY_PATH
    info = {
        "current_scheme": request.url.scheme,
        "https_active": request.url.scheme == "https",
        "https_enabled_setting": _get_setting("https_enabled") == "1",
        "ssl_custom": _get_setting("ssl_custom") == "1",
        "cert_path": str(cert_path),
        "key_path": str(key_path),
        "cert_exists": cert_path.exists(),
        "cert_subject": None,
        "cert_not_after": None,
        "cert_sans": [],
    }
    if cert_path.exists():
        try:
            from cryptography import x509
            cert = x509.load_pem_x509_certificate(cert_path.read_bytes())
            info["cert_subject"] = cert.subject.rfc4514_string()
            info["cert_not_after"] = cert.not_valid_after_utc.isoformat()
            try:
                san = cert.extensions.get_extension_for_class(x509.SubjectAlternativeName).value
                info["cert_sans"] = [str(g.value) for g in san]
            except Exception:
                pass
        except Exception as e:
            info["cert_error"] = str(e)
    return info


