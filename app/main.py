# Tell browsers not to cache JSON API responses — without this, GET /api/items/{id}
# polling can return stale "analyzing" status long after the AI is done.
@app.middleware("http")
async def no_cache_api(request, call_next):
    response = await call_next(request)
    if request.url.path.startswith("/api/"):
        response.headers["Cache-Control"] = "no-store, must-revalidate"
        response.headers["Pragma"] = "no-cache"
    return response

# Apply any persisted LLM endpoint override from the settings table at startup.
def _apply_persisted_settings() -> None:
    with tx() as conn:
        url = conn.execute("SELECT value FROM settings WHERE key='llm_base_url'").fetchone()
        model = conn.execute("SELECT value FROM settings WHERE key='llm_model'").fetchone()
        fmv_rows = conn.execute(
            "SELECT category_key, low, median, high FROM fmv_overrides"
        ).fetchall()
    if url and url["value"]:
        vision.set_base_url(url["value"])
    if model and model["value"]:
        vision.set_model_override(model["value"])
    fmv.load_overrides([dict(r) for r in fmv_rows])

    # Auto-detect a hand-placed cert in data/certs/. If a cert exists and was
    # NOT generated by our self-signer, mark it as user-supplied so the
    # status panel labels it correctly.
    detected = tls.is_self_signed_by_us()
    if detected is False:
        with tx() as conn:
            conn.execute(
                "INSERT INTO settings(key,value) VALUES('ssl_custom','1') "
                "ON CONFLICT(key) DO UPDATE SET value='1'"
            )
    elif detected is True:
        # If we previously thought a custom cert was installed but the file
        # is now self-signed, clear the flag.
        with tx() as conn:
            conn.execute("DELETE FROM settings WHERE key='ssl_custom'")
_apply_persisted_settings()


