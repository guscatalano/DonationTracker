    """Delete the existing cert (custom or self-signed) and create a fresh
    self-signed one covering every current LAN IP."""
    try:
        if tls.CERT_PATH.exists(): tls.CERT_PATH.unlink()
        if tls.KEY_PATH.exists(): tls.KEY_PATH.unlink()
    except Exception as e:
        raise HTTPException(500, f"could not remove old cert: {e}")
